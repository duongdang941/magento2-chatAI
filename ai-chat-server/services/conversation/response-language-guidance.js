export const RESPONSE_LANGUAGE_AGENT_GUIDANCE = `RESPONSE LANGUAGE CONTRACT:
- Determine the response language from the grammatical/request words in the shopper's latest message. A product name, search term, brand, SKU, quoted phrase, catalogue label, tool result, or store locale must never change the response language.
- For mixed-language requests, keep the language used by the shopper to form the request. Preserve foreign product names and catalogue option labels only as data.
- Every catalogue tool call must set responseLanguage to the BCP-47 language tag selected from that grammatical frame. Keep the same tag through all retrieval rounds in the turn.
- Before emitting customer-visible text, silently verify that headings, explanations, price labels, availability labels, links, and follow-up questions use responseLanguage.`;

const RESPONSE_LANGUAGE_NAMES = Object.freeze({
    de: 'German',
    en: 'English',
    vi: 'Vietnamese'
});

const RESPONSE_LANGUAGE_WORDS = Object.freeze({
    de: new Set(['aber', 'bitte', 'danke', 'das', 'der', 'die', 'du', 'ein', 'eine', 'für', 'hallo', 'ich', 'ist', 'mit', 'nicht', 'und', 'was', 'wie']),
    en: new Set(['can', 'could', 'hello', 'help', 'hey', 'hi', 'how', 'please', 'thank', 'thanks', 'the', 'what', 'where', 'with', 'would']),
    vi: new Set(['ban', 'bạn', 'can', 'cần', 'chao', 'chào', 'cho', 'có', 'cua', 'của', 'giup', 'giúp', 'khong', 'không', 'minh', 'mình', 'muon', 'muốn', 'nay', 'này', 'toi', 'tôi', 'viet', 'viết', 'xin'])
});

function languageExplicitlyRequested(message) {
    // The shopper may write Vietnamese without diacritics (for example
    // "dung tieng anh de tra loi").  Normalise only for language-selection
    // intent; this never changes the original message, catalogue data, or
    // customer-facing copy generated by the model.
    const text = String(message || '')
        .trim()
        .toLocaleLowerCase()
        .normalize('NFD')
        .replace(/\p{M}/gu, '')
        .replaceAll('đ', 'd');
    const requested = [
        ['vi', /(?:reply|respond|answer|speak|write|use)\s+(?:in\s+)?vietnamese\b|(?:tra loi|noi|viet|dung)\s+(?:(?:bang|tieng)\s+)?viet\b/u],
        ['en', /(?:reply|respond|answer|speak|write|use)\s+(?:in\s+)?english\b|(?:tra loi|noi|viet|dung)\s+(?:(?:bang|tieng)\s+)?anh\b/u],
        ['de', /(?:reply|respond|answer|speak|write|use)\s+(?:in\s+)?german\b|(?:tra loi|noi|viet|dung)\s+(?:(?:bang|tieng)\s+)?duc\b/u]
    ];
    return requested.find(([, pattern]) => pattern.test(text))?.[0] || '';
}

export function inferResponseLanguage(shopperMessage) {
    const message = String(shopperMessage || '').trim();
    if (!message) return '';

    const explicitLanguage = languageExplicitlyRequested(message);
    if (explicitLanguage) return explicitLanguage;

    const normalized = message.toLocaleLowerCase();
    const scores = { de: 0, en: 0, vi: 0 };
    const words = normalized.match(/\p{L}+/gu) || [];

    // Common accented Latin letters such as é/í occur in Spanish, French,
    // and many other languages. They must not make a Spanish customer look
    // Vietnamese merely because this gateway also supports Vietnamese.
    // Vietnamese-specific letters still provide strong positive evidence;
    // ordinary Vietnamese requests are additionally scored by request words.
    if (/[ăâđêôơư]/u.test(normalized)) {
        scores.vi += 3;
    }
    if (/[äöüß]/u.test(normalized)) {
        scores.de += 3;
    }

    for (const word of words) {
        for (const [language, knownWords] of Object.entries(RESPONSE_LANGUAGE_WORDS)) {
            if (knownWords.has(word)) scores[language] += 1;
        }
    }

    const ranked = Object.entries(scores).sort(([, left], [, right]) => right - left);
    if (!ranked[0] || ranked[0][1] < 1 || ranked[0][1] === ranked[1]?.[1]) return '';
    return ranked[0][0];
}

export function turnResponseLanguageInstruction(shopperMessage) {
    const language = inferResponseLanguage(shopperMessage);
    const name = RESPONSE_LANGUAGE_NAMES[language];
    if (!name) return '';

    return `RESPONSE LANGUAGE LOCK FOR THIS TURN: ${name} (${language}). This overrides the language used in earlier conversation turns. Write all customer-facing prose in ${name} only. Do not add a translation, duplicate greeting, or any other customer-facing text in another language unless the shopper explicitly requests it.`;
}

export function normalizeResponseLanguage(value) {
    const language = String(value || '').trim();
    if (!language || language.length > 35 || !/^[\p{L}]{2,20}(?:[- ][\p{L}]{2,20}){0,2}$/u.test(language)) {
        return '';
    }
    return language;
}

/**
 * Compare BCP-47 tags by their primary language without imposing a locale on
 * the model.  `en`, `en-US`, and `en-GB` are the same customer language for
 * a turn-level action contract, while an invalid model value never passes.
 */
export function primaryResponseLanguageTag(value) {
    const language = normalizeResponseLanguage(value);
    return language ? language.split(/[- ]/u, 1)[0].toLocaleLowerCase() : '';
}

export function normalizeResponseLanguageEvidence(evidence, shopperMessage, catalogQuery = '') {
    const message = String(shopperMessage || '').toLocaleLowerCase();
    const query = String(catalogQuery || '').toLocaleLowerCase();
    const seen = new Set();

    return (Array.isArray(evidence) ? evidence : [])
        .map(item => String(item || '').trim())
        .filter(item => /^[\p{L}\p{N}'’_-]{1,40}$/u.test(item))
        .filter(item => {
            const normalized = item.toLocaleLowerCase();
            if (seen.has(normalized) || !message.includes(normalized) || query.includes(normalized)) {
                return false;
            }
            seen.add(normalized);
            return true;
        })
        .slice(0, 8);
}

export function responseLanguageInstruction(
    value,
    evidence = [],
    shopperMessage = '',
    catalogQuery = ''
) {
    const safeEvidence = normalizeResponseLanguageEvidence(evidence, shopperMessage, catalogQuery);
    if (safeEvidence.length >= 2) {
        return `RESPONSE LANGUAGE FOR THIS TURN is the language formed by these verified shopper request words: ${JSON.stringify(safeEvidence)}. Use those grammatical words—not the product query, catalogue names, store locale, or a model-supplied language label—to select the language. Write all customer-facing prose and UI labels in that language; preserve foreign catalogue names only as product data.`;
    }

    const language = normalizeResponseLanguage(value);
    if (!language) {
        return 'Use the language formed by the shopper’s grammatical/request words. Ignore catalogue-language evidence when choosing the response language.';
    }

    return `RESPONSE LANGUAGE FOR THIS TURN: ${language}. Write all customer-facing prose and UI labels in this language. Keep foreign catalogue names only as unchanged product data.`;
}
